/**
 * Dev-only tool. Bundles the assistant's knowledge into a committed TS module
 * (`src/lib/chat/knowledge.generated.ts`) so the build and runtime never read a
 * file — the generated module IS the source of truth at build time. This is why
 * it is NOT wired into `build` / `prebuild`: the deploy only has this repo, and
 * the One Piece doc lives one level up in the bot repo.
 *
 * Sources:
 *   ../../documents/onepiece_theory.md      (bot repo — source of truth)
 *   src/content/daily-challenges-guide.md   (hand-authored, this repo)
 *
 * Run it locally after editing either source, then commit the regenerated file:
 *   npm run sync-knowledge
 *
 * If a source is missing (e.g. run outside the full checkout) it leaves the
 * existing generated file untouched and exits 0.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");

const ONEPIECE_SRC = resolve(repoRoot, "..", "documents", "onepiece_theory.md");
const GUIDE_SRC = resolve(repoRoot, "src", "content", "daily-challenges-guide.md");
const OUT = resolve(repoRoot, "src", "lib", "chat", "knowledge.generated.ts");

function read(path, label) {
  if (!existsSync(path)) {
    console.warn(
      `[sync-knowledge] missing ${label}: ${path}\n` +
        `[sync-knowledge] leaving ${OUT} as-is and exiting.`,
    );
    return null;
  }
  return readFileSync(path, "utf8").trim();
}

/** Safe embedding inside a TS backtick template literal. */
function asTemplate(text) {
  return "`" + text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${") + "`";
}

const onepiece = read(ONEPIECE_SRC, "One Piece knowledge doc");
const guide = read(GUIDE_SRC, "daily-challenges guide");

if (onepiece === null || guide === null) {
  process.exit(0);
}

const body = `// GENERATED by scripts/sync-knowledge.mjs — do not edit by hand.
// Re-run \`npm run sync-knowledge\` after changing either source document.

export const ONE_PIECE_KNOWLEDGE = ${asTemplate(onepiece)};

export const DAILY_CHALLENGES_GUIDE = ${asTemplate(guide)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body, "utf8");

console.log(
  `[sync-knowledge] wrote ${OUT}\n` +
    `  One Piece doc: ${onepiece.length} chars\n` +
    `  Site guide:    ${guide.length} chars`,
);
